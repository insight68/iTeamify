    expect(unauthorized.status).toBe(404);
    const contact=pageB.locator('[data-slot="sidebar-content"]').getByRole("link",{name:/Contract Alice/});
    await expect(contact.getByRole("img",{name:"Unread messages"})).toBeVisible();
    await pageB.goto(`/${workspace.slug}/chat?member=${a.user.id}&session=${sid}`);
    await pageB.getByRole("button",{name:"Accept request",exact:true}).click();
    await expect(pageB.getByText("Accepted",{exact:true}).first()).toBeVisible();

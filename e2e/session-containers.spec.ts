    expect((await frozen.json()).configuration.require_focus).toBe(false);
    const unavailable=await fetch(`${apiBase}/api/session-applications?target_kind=member&target_id=${b.user.id}`,{headers:{Authorization:`Bearer ${alice.getToken()}`,"X-Workspace-ID":workspace.id}});
    expect((await unavailable.json()).providers).toEqual([]);
    await pageA.goto(`/${workspace.slug}/chat?member=${b.user.id}&new=${crypto.randomUUID()}&container=contract_review`);
    await expect(pageA.getByRole("alert").filter({hasText:"has paused the service"})).toBeVisible();
    await expect(pageA.getByRole("button",{name:"Submit request",exact:true})).toBeDisabled();
    const runtime=await db.query(`INSERT INTO agent_runtime(workspace_id,name,runtime_mode,provider,status,device_info,metadata,last_seen_at) VALUES($1,'Contract fixture runtime','cloud','e2e_contract','online','Test runtime','{}',now()) RETURNING id`,[workspace.id]);
    const agent=await db.query(`INSERT INTO agent(workspace_id,name,runtime_mode,runtime_config,visibility,max_concurrent_tasks,owner_id,runtime_id) VALUES($1,'Contract Assistant','cloud','{}','workspace',1,$2,$3) RETURNING id`,[workspace.id,a.user.id,runtime.rows[0].id]);
    const configuration=await fetch(`${apiBase}/api/session-applications`,{method:"POST",headers:{Authorization:`Bearer ${alice.getToken()}`,"X-Workspace-ID":workspace.id,"Content-Type":"application/json"},body:JSON.stringify({target_kind:"agent",target_id:agent.rows[0].id,status:"enabled",version:0,config:{service_name:"AI contract review",description:"Review by AI",contract_types:[],require_background:false,require_focus:false,default_priority:"normal",review_instructions:"Read all files",result_requirements:"Save a concrete result",agent_instructions:"Request missing information"}})});

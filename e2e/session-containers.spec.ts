    expect(await pageA.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await pageA.screenshot({path:testInfo.outputPath("contract-mobile.png"),fullPage:true});
    await pageA.setViewportSize({width:1280,height:800});
    await pageA.goto(`/${workspace.slug}/applications`);
    await pageA.getByRole("button",{name:"Manage configurations",exact:true}).click();
    await pageA.getByRole("button",{name:"Edit configuration",exact:true}).click();
    await pageA.getByLabel("Require review focus",{exact:true}).check();

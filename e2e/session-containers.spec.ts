    await expect(pageB.getByRole("button",{name:"Manage configurations",exact:true})).toHaveCount(0);
    await pageA.goto(`/${workspace.slug}/chat?member=${c.user.id}&view=list`);
    await pageA.getByRole("button",{name:"New session",exact:true}).click();
    await expect(pageA).toHaveURL(/container=conversation/);
    await pageA.goto(`/${workspace.slug}/applications`);
    await pageA.getByRole("button",{name:"Manage configurations",exact:true}).click();
    await pageA.getByRole("button",{name:"Add configuration",exact:true}).click();
    await pageA.getByLabel("Service provider",{exact:true}).selectOption(`member:${b.user.id}`);
    await pageA.getByLabel("Public service description",{exact:true}).fill("Review procurement agreements");
    await pageA.getByLabel("Require business context",{exact:true}).check();
    await pageA.getByLabel("Review instructions",{exact:true}).fill("Check payment deadlines and liability caps");
    await pageA.getByRole("button",{name:"Save draft",exact:true}).click();
    await expect(pageA.getByRole("dialog")).toHaveCount(0);
    await pageA.getByRole("button",{name:"Service providers",exact:true}).click();
    await expect(pageA.getByText("No available service providers",{exact:true})).toBeVisible();
    await pageA.getByRole("button",{name:"Manage configurations",exact:true}).click();
    await pageA.getByRole("button",{name:"Edit configuration",exact:true}).click();
    await pageA.getByRole("button",{name:"Enable",exact:true}).click();
    await expect(pageA.getByRole("dialog")).toHaveCount(0);
    await pageA.getByRole("button",{name:"Service providers",exact:true}).click();
    await expect(pageA.getByRole("link",{name:"Contact provider",exact:true})).toBeVisible();
    await pageA.screenshot({path:testInfo.outputPath("applications-desktop.png"),fullPage:true});
    await pageA.setViewportSize({width:390,height:844});
    expect(await pageA.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
    await pageA.screenshot({path:testInfo.outputPath("applications-mobile.png"),fullPage:true});
    await pageA.setViewportSize({width:1280,height:800});
    const beforeSessionCount=(await db.query("SELECT count(*)::int n FROM chat_session WHERE workspace_id=$1",[workspace.id])).rows[0].n;
    await pageA.getByRole("link",{name:"Contact provider",exact:true}).click();
    expect((await db.query("SELECT count(*)::int n FROM chat_session WHERE workspace_id=$1",[workspace.id])).rows[0].n).toBe(beforeSessionCount);
    await pageA.getByRole("button",{name:"New session",exact:true}).click();
    await pageA.getByRole("menuitem",{name:"Contract review",exact:true}).click();
    await pageA.getByLabel("Request title",{exact:true}).fill("Supply agreement review");
    await pageA.getByLabel("Contract type",{exact:true}).fill("Supply agreement");

-- Restore the 587 shape: drop the four delete audit columns from the view.
-- Safe to roll back at any time -- the columns are pure pass-through and no
-- stored data lives in the view.
CREATE OR REPLACE VIEW crm_customer_records AS
SELECT a.id, a.workspace_id, 'account'::text AS record_type, a.id AS account_id,
 NULL::uuid AS lead_id, 'approved'::text AS review_status,
 a.account_type AS lead_type, a.domain, a.website_url,
 '[]'::jsonb AS emails, '[]'::jsonb AS phones,
 a.display_name,
 a.company_name,
 a.country,
 a.industry,
 a.priority,
 a.notes,
 a.tags,
 a.custom_fields,
 a.first_contact_at,
 a.last_contact_at,
 a.next_follow_up_at,
 a.primary_opportunity_id,
 a.score_override,
 a.score_override_reason,
 a.score_override_by_member_id,
 a.score_override_at,
 a.score_override_expires_at,
 a.parked_at,
 a.park_reason,
 a.park_source,
 a.parked_by_member_id,
 a.record_status,
 a.owner_member_id,
 a.version,
 a.created_at,
 a.updated_at
FROM accounts a
UNION ALL
SELECT l.id,l.workspace_id,'lead'::text,NULL::uuid,l.id,l.review_status,
 l.lead_type,COALESCE(l.domain,''),l.website_url,l.emails,l.phones,
 l.display_name,
 l.company_name,
 l.country,
 l.industry,
 l.priority,
 l.notes,
 l.tags,
 l.custom_fields,
 l.first_contact_at,
 l.last_contact_at,
 l.next_follow_up_at,
 l.primary_opportunity_id,
 l.score_override,
 l.score_override_reason,
 l.score_override_by_member_id,
 l.score_override_at,
 l.score_override_expires_at,
 l.parked_at,
 l.park_reason,
 l.park_source,
 l.parked_by_member_id,
 l.record_status,
 l.owner_member_id,
 l.version,
 l.created_at,
 l.updated_at
FROM leads l WHERE l.account_id IS NULL;

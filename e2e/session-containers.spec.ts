    await authenticate(contextA,alice);await authenticate(contextB,bob);
    const pageA=await contextA.newPage(),pageB=await contextB.newPage();
    pageA.setDefaultTimeout(20000); pageB.setDefaultTimeout(20000);
    const errors: string[]=[];

    await pageA.getByRole("button",{name:"Download agreement.txt",exact:true}).click();
    expect((await download).suggestedFilename()).toBe("agreement.txt");
    await pageA.getByRole("button",{name:"Discussion",exact:true}).click();
    await pageA.getByRole("textbox",{name:/Contract Bob/}).fill("Please confirm the final amendment");

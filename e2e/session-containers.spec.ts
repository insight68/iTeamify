    await pageA.getByLabel("Review focus",{exact:true}).fill("Payment and late delivery clauses");
    await pageA.locator("#contract-files").setInputFiles({name:"agreement.txt",mimeType:"text/plain",buffer:Buffer.from("Payment is due within 30 days. Late delivery incurs a fee.")});
    // A structured request mounts no conversation composer or transcript.
    await expect(pageA.locator('[contenteditable="true"]')).toHaveCount(0);
    await expect(pageA.getByRole("log")).toHaveCount(0);
    await pageA.getByRole("button",{name:"Submit request",exact:true}).click();
    await expect(pageA).toHaveURL(/session=/);
    const sid=new URL(pageA.url()).searchParams.get("session")!;
    await expect(pageA.getByRole("heading",{name:"Supply agreement review",exact:true})).toBeVisible();
    expect((await db.query("SELECT count(*)::int n FROM chat_message WHERE chat_session_id=$1",[sid])).rows[0].n).toBe(0);
    const apiBase=`http://localhost:${process.env.PORT}`;
